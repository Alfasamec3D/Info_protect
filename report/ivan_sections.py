LABELS = {'single': 'Разные запросы', 'majority_5': 'Большинство пяти', 'soft_5': 'Доля из пяти'}


def load(results):
    from build import read_csv
    return {study: {name: read_csv(results / 'ivan' / study, name)
                    for name in ('summary', 'contrasts')}
            for study in ('confirmation', 'stopping')}


def primary(data):
    return [r for r in data['ivan']['stopping']['contrasts'] if r['primary'] == 'True']


def stopping_metric(data, row, method):
    return next(r for r in data['ivan']['stopping']['summary'] if r['method'] == method
                and all(float(r[k]) == float(row[k]) for k in ('sigma', 'budget', 'cap')))


def reduction(data, row):
    return -100 * float(row['difference']) / float(stopping_metric(data, row, 'unweighted')['probability_mse'])


def decimal(value, digits=3):
    return f'{float(value):.{digits}f}'.replace('.', ',')


def result_sentence(data):
    values = [reduction(data, r) for r in primary(data)]
    return (f'В дополнении из ветки Ivan учёт фактического числа чтений после адаптивной остановки '
            f'снизил MSE вероятности на {decimal(min(values),1)}–{decimal(max(values),1)}% '
            'относительно невзвешенных долей. Восемь парных интервалов с поправкой Бонферрони '
            'исключают ноль; оценка выполнена на 100 независимых Arbiter PUF.')


def confirmation_rows(data):
    from build import pct
    return [[LABELS[r['strategy']], pct(r['accuracy']), pct(r['noisy_accuracy']), str(int(float(r['train_unique'])))]
            for r in data['ivan']['confirmation']['summary']]


def stopping_rows(data):
    rows = []
    for r in primary(data):
        rows.append([decimal(r['sigma'],2), r['budget'], r['cap'],
                     decimal(1000 * float(stopping_metric(data,r,'unweighted')['probability_mse'])),
                     decimal(1000 * float(stopping_metric(data,r,'count_likelihood')['probability_mse'])),
                     decimal(reduction(data,r),1),
                     f"[{decimal(1000*float(r['ci_low']))}; {decimal(1000*float(r['ci_high']))}]"])
    return rows


