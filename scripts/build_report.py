section('2. Модель PUF и шум', '''Challenge — вектор c длины n=64 со значениями −1 и +1. Соответствие битам: 0 → +1, 1 → −1. При таком кодировании XOR ответов соответствует произведению.

Признаки задаются суффиксными произведениями:
φ_i(c) = произведение c_j по j от i до n−1; φ_n(c)=1.
Задержка одной цепочки: Δ(c)=w·φ(c).
Ответ цепочки: r(c)=+1 при Δ(c)≥0, иначе −1.
Для k цепочек ответ R(c)=произведение r_l(c).

Веса каждой цепочки независимо генерируются из N(0,1/(n+1)). Это фиксирует приблизительно единичную дисперсию задержки по ансамблю экземпляров. Такой закон распределения — допущение симулятора, а не модель конкретного процесса изготовления.

Физическая интерпретация проверена независимо от функции признаков. Для рекурсии этапов Δ_i=c_i·Δ_(i−1)+a_i·c_i+b_i её развёртывание даёт w_0=a_0, w_i=a_i+b_(i−1), bias=b_(n−1). Тест сравнивает поэтапный расчёт с векторным на случайных параметрах.

При измерении добавляется независимый гауссовский шум ε_l~N(0,σ²) к задержке каждой цепочки. Затем применяется знак и XOR. σ — масштаб задержки, а не вероятность инверсии бита. Повторы независимы при фиксированном challenge и весах. Коррелированный шум, дрейф температуры и систематические ошибки не моделируются.

Пусть Φ — функция распределения стандартного нормального закона. Для σ>0 точная вероятность положительного ответа XOR равна p(c)=[1+произведение(2Φ(Δ_l/σ)−1)]/2. Она применяется только оценщиком; атака не получает задержки, веса или p(c).''')
section('3. Реализованные атаки', '''Все обучаемые модели получают только challenge и наблюдаемые метки.

majority: постоянный ответ, соответствующий большинству обучающих меток. Это контроль смещения выходов.

raw_lr: логистическая регрессия непосредственно на исходных битах challenge. Проверяет влияние правильного представления входа.

lr: логистическая регрессия на φ(c). Оптимизируется средняя бинарная кросс-энтропия (BCE) с L2=10⁻⁵. Свободный коэффициент линейной модели не штрафуется. Используется L-BFGS-B, максимум 400 итераций.

xor_lr: структурная нелинейная модель p(c)=[1+произведение tanh(v_l·φ(c))]/2. Количество факторов равно публичному k. Факторы моделируют цепочки, но не получают их индивидуальные ответы. Минимизируется BCE с малой численной стабилизацией и L2=10⁻⁵. Это собственная реализация известного принципа использования структуры XOR, не заявка на новую архитектуру.

mlp: 65 входов, один скрытый слой из 32 tanh-нейронов, один сигмоидальный выход. Для xor_lr и mlp используется Adam с шагом 0.01, batch=256, максимум 100 эпох, три перезапуска. Чекпоинт выбирается по минимальной валидационной потере. Ранняя остановка — после 18 эпох без улучшения более 10⁻⁵.

Аналитические градиенты lr, xor_lr и mlp проверены конечными разностями. Отдельный тест подтверждает обучение 2-XOR на малой задаче. Неуспех отдельных нелинейных запусков ожидаем при ограниченных данных и бюджете оптимизации и должен отражаться в результатах.''')
