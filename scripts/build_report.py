def load(name,file='summary.csv'):
    with (ROOT/'results'/name/file).open() as f:
        return list(csv.DictReader(f))


def get(rows,**query):
    matches=[r for r in rows if all(str(r[k])==str(v) for k,v in query.items())]
    if len(matches)!=1:
        raise ValueError((query,len(matches)))
    return matches[0]


def pct(value):
    return f'{100*float(value):.2f}%'


def interval(row,metric='accuracy'):
    return f"{pct(row[metric])} [{pct(row[metric+'_ci_low'])}; {pct(row[metric+'_ci_high'])}]"


def wrap(text,width=76):
    lines=[]
    for p in text.split('\n'):
        lines.extend(textwrap.wrap(p,width=width,break_long_words=True,break_on_hyphens=False) or [''])
    return lines


def text_pages(pdf,title,text,page_number):
    lines=wrap(text)
    for offset in range(0,len(lines),35):
        fig=plt.figure(figsize=(8.27,11.69),facecolor='white')
        fig.text(.09,.94,title if offset==0 else title+' (продолжение)',fontsize=16,weight='bold',va='top')
        body=fig.text(.09,.875,'\n'.join(lines[offset:offset+35]),fontsize=10.5,linespacing=1.65,va='top')
        fig.canvas.draw()
        box=body.get_window_extent(fig.canvas.get_renderer()).transformed(fig.transFigure.inverted())
        if box.y0 < .08 or box.x1 > .96:
            raise ValueError(f'text overflow: {title} {box}')
        if title.startswith('7.') and offset==0:
            fig.savefig('/tmp/puf-report-preview.png',dpi=100)
        fig.text(.09,.045,'Реализация атак на PUF • вычислительное исследование',fontsize=8,color='#555555')
        fig.text(.91,.045,str(page_number),ha='right',fontsize=9)
        pdf.savefig(fig)
        plt.close(fig)
        page_number+=1
    return page_number


def figure_page(pdf,title,paths,page_number,caption):
    fig=plt.figure(figsize=(8.27,11.69),facecolor='white')
    fig.text(.08,.95,title,fontsize=16,weight='bold',va='top')
    for i,path in enumerate(paths):
        y=.51 if i==0 else .13
        ax=fig.add_axes([.06,y,.88,.36])
        ax.imshow(plt.imread(path))
        ax.axis('off')
    fig.text(.08,.075,'\n'.join(wrap(caption,92)),fontsize=9,va='top')
    fig.text(.92,.035,str(page_number),ha='right',fontsize=9)
    pdf.savefig(fig)
    plt.close(fig)
    return page_number+1


